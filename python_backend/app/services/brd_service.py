    # ─────────────────────────────────────────────
    # DB helper
    # ─────────────────────────────────────────────
    def _get_analysis_from_db(self, repo_identifier: str) -> dict:
        from app.database import SessionLocal
        from app.db_models import Repository, Analysis
        db = SessionLocal()
        try:
            repo = (
                db.query(Repository).filter(Repository.name == repo_identifier).first()
                or db.query(Repository).filter(Repository.repo_url == repo_identifier).first()
            )
            if not repo:
                raise Exception(
                    f"No repository found for '{repo_identifier}'. "
                    "Please run repository analysis first."
                )
            analysis = (
                db.query(Analysis)
                .filter(Analysis.repository_id == repo.id)
                .order_by(Analysis.created_at.desc())
                .first()
            )
            if not analysis:
                raise Exception(
                    f"No analysis found for '{repo_identifier}'. "
                    "Please run repository analysis first."
                )
            return {
                "repo_url":     repo.repo_url or "",
                "repo_name":    repo.name or repo.repo_url.split("/")[-1].replace(".git", ""),
                "project_type": analysis.project_type or "Unknown",
                "framework":    analysis.framework or "Unknown",
                "build_tool":   analysis.build_tool or "Unknown",
                "database":     analysis.database_type or "Unknown",
                "is_java":      (analysis.project_type or "").lower() == "java",
                "stored_brd":   analysis.full_brd_report or {},
            }
        finally:
            db.close()
 
