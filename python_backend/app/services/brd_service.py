    def generate_brd_html(self, repo_identifier: str) -> str:
        """Load analysis from DB, map to template vars, render HTML."""
        context = self._get_analysis_from_db(repo_identifier)
 
        # Initialise all template keys to a hyphen
        template_file = self.env.get_template("brd_full_template.html").filename
        with open(template_file, "r", encoding="utf-8") as f:
            raw_template = f.read()
        all_keys = list(set(re.findall(r'\{\{\s*([A-Za-z0-9_]+)\s*\}\}', raw_template)))
        template_vars = {k: "-" for k in all_keys}
 
        # Enrich sparse stored data with intelligent fallbacks
        enriched_context = dict(context)
        enriched_context["stored_brd"] = self._enrich_sparse_brd(context["stored_brd"], context)
 
        # Map stored analysis data to template vars
        mapped = self._map_to_template(enriched_context)
        template_vars.update(mapped)
 
        # Render
        template = self.env.get_template("brd_full_template.html")
        return template.render(template_vars)
 
 
