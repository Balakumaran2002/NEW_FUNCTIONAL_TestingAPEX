    # Helper utilities
    # ─────────────────────────────────────────────
    @staticmethod
    def _s(value, fallback="-") -> str:
        """Safely convert any value to a non-empty string."""
        if value is None:
            return fallback
        if isinstance(value, (list, dict)):
            return json.dumps(value)
        return str(value).strip() or fallback
 
    @staticmethod
    def _list_item(lst, idx, key=None, fallback="-") -> str:
        """Get the idx-th item from a list (0-based), optionally extracting a key."""
        if not isinstance(lst, list) or idx >= len(lst):
            return fallback
        item = lst[idx]
        if key and isinstance(item, dict):
            return str(item.get(key, fallback)).strip() or fallback
        return str(item).strip() or fallback
 
    @staticmethod
    def _join(lst, sep=", ", key=None) -> str:
        """Join a list into a string."""
        if not isinstance(lst, list):
            return ""
        parts = []
        for item in lst:
            if key and isinstance(item, dict):
                parts.append(str(item.get(key, "")))
            else:
                parts.append(str(item))
        return sep.join(p for p in parts if p)
 
